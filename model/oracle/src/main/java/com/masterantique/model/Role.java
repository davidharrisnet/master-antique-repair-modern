package com.masterantique.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/** One row of {@code roles}: Customer, Employee, Manager (ids 1-3 after the migration). Read-only in practice. */
@Entity
@Table(name = "roles")
public class Role {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)   // GENERATED BY DEFAULT AS IDENTITY
    private Integer id;

    @Column(name = "name", nullable = false, length = 256)
    private String name;                                  // unique (ix_roles_name)

    protected Role() {
    }

    public Integer getId() { return id; }
    public String getName() { return name; }
}
